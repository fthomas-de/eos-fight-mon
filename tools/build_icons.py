"""Build ship_icons.json (every published ship of the EVE SDE with its 32 px icon, packed into the exe)
and drones.py (every published drone and fighter type name, so fights can tell them from ships).

Run before a release build when new ships or drones came out:  python tools/build_icons.py
Only compare the SDE build used with CCP's latest (exit 1 if outdated):  python tools/build_icons.py --check
"""
import base64
import io
import json
import sys
import time
import urllib.request
import zipfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

SDE = "https://developers.eveonline.com/static-data/tranquility/"
ICON = "https://images.evetech.net/types/{}/icon?size=32"
SHIP_CATEGORY = 6
DRONE_CATEGORIES = {18, 87}  # drones, fighters
OUT = Path(__file__).resolve().parent.parent / "ship_icons.json"
DRONES_OUT = OUT.with_name("drones.py")


def get(url, tries=8):
    for attempt in range(tries):  # CCP's servers drop the odd handshake
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "eos-fight-mon build"})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except OSError:
            if attempt == tries - 1:
                raise
            time.sleep(0.5 * (attempt + 1))


def main():
    build = json.loads(get(SDE + "latest.jsonl").splitlines()[0])["buildNumber"]
    if "--check" in sys.argv[1:]:  # only compare, download nothing
        try:
            used = json.loads(OUT.read_text(encoding="utf-8"))["sde_build"]
        except (OSError, ValueError, KeyError):
            used = None
        print(f"SDE build used: {used}, latest: {build} -> {'up to date' if used == build else 'rebuild'}")
        sys.exit(used != build)
    print(f"SDE build {build}: downloading …")
    sde = zipfile.ZipFile(io.BytesIO(get(f"{SDE}eve-online-static-data-{build}-jsonl.zip")))

    def rows(name):
        with sde.open(name) as fh:
            return [json.loads(line) for line in fh]

    category = {g["_key"]: g["categoryID"] for g in rows("groups.jsonl")}
    types = [t for t in rows("types.jsonl") if t.get("published")]
    ships = {t["name"]["en"]: t["_key"] for t in types if category.get(t["groupID"]) == SHIP_CATEGORY}
    drones = sorted({t["name"]["en"] for t in types if category.get(t["groupID"]) in DRONE_CATEGORIES})
    DRONES_OUT.write_text('"""Generated by tools/build_icons.py."""\n'
                          f"SDE_BUILD = {build}\n"
                          "DRONE_TYPES = frozenset({\n" + "".join(f"    {n!r},\n" for n in drones) + "})\n",
                          encoding="utf-8")
    print(f"wrote {DRONES_OUT.name}: {len(drones)} drone and fighter types")
    print(f"{len(ships)} ships, fetching icons …")

    with ThreadPoolExecutor(4) as pool:  # polite to CCP's image server
        pngs = dict(zip(ships, pool.map(lambda type_id: get(ICON.format(type_id)), ships.values())))
    bad = [name for name, png in pngs.items() if not png.startswith(b"\x89PNG")]
    assert not bad, f"not a PNG: {bad[:5]}"

    icons = {name: base64.b64encode(png).decode() for name, png in sorted(pngs.items())}
    OUT.write_text(json.dumps({"sde_build": build, "icons": icons}, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(icons)} icons, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
